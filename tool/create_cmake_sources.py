# Directories scanned. Other platform/ and port/ directories are port specific
SCAN = ["src", "platform/embedded", "platform/lwip", "3rd-party"]

# Third party projects ship their own tests and examples
SKIP_DIRS = {"test", "tests", "example", "examples", "doc", "docs"}


def matches(rel, pattern):
    """Glob match where '*' stays within a path segment and '**' spans segments."""
    regex = ""
    i = 0
    while i < len(pattern):
        if pattern.startswith("**", i):
            regex += ".*"
            i += 2
        elif pattern[i] == "*":
            regex += "[^/]*"
            i += 1
        else:
            regex += re.escape(pattern[i])
            i += 1
    return re.fullmatch(regex, rel) is not None


def list_name(rule_name, rel):
    if not rule_name.endswith("*"):
        return rule_name
    if rule_name.startswith("THIRD_PARTY"):
        key = rel.split("/")[1]
    else:
        key = os.path.basename(rel)[:-len(".c")]
        # UTIL_* etc read better without the btstack_ prefix repeated
        key = re.sub(r"^btstack_", "", key)
    return rule_name[:-1] + re.sub(r"[^A-Za-z0-9]", "_", key).upper()


def classify(rel):
    for pattern, name in RULES:
        if matches(rel, pattern):
            return list_name(name, rel)
    return None


def main():
    root = os.path.abspath(os.path.dirname(sys.argv[0]) + "/..")
    lists, unclassified = {}, []

    for scan in SCAN:
        for dirpath, dirnames, filenames in os.walk(os.path.join(root, scan)):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
            for fn in sorted(filenames):
                if not fn.endswith(".c"):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, fn), root).replace(os.sep, "/")
                name = classify(rel)
                if name is None:
                    unclassified.append(rel)
                else:
                    lists.setdefault(name, []).append(rel)

    out = os.path.join(root, "tool/cmake/BTstackSources.cmake")
    with open(out, "w") as f:
        f.write(HEADER)
        f.write("set(BTSTACK_SOURCE_LISTS\n")
        for name in sorted(lists):
            f.write("    %s\n" % name)
        f.write(")\n\n")
        for name in sorted(lists):
            f.write("set(BTSTACK_%s_SOURCES\n" % name)
            for rel in sorted(lists[name]):
                f.write("    %s\n" % rel)
            f.write(")\n\n")
        # Only emitted when non-empty: normally every source is in a list
        #   if (BTSTACK_UNCLASSIFIED_SOURCES)
        #       message(WARNING "BTstack has sources in no list")
        #   endif()
        if unclassified:
            f.write("# No rule in tool/create_cmake_sources.py matched these.\n")
            f.write("set(BTSTACK_UNCLASSIFIED_SOURCES\n")
            for rel in sorted(unclassified):
                f.write("    %s\n" % rel)
            f.write(")\n")

    print("wrote %s: %d lists, %d files" %
          (os.path.relpath(out, root), len(lists), sum(len(v) for v in lists.values())))
    if unclassified:
        print("WARNING: %d file(s) matched no rule:" % len(unclassified), file=sys.stderr)
        for rel in unclassified:
            print("   ", rel, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
