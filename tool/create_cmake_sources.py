# This generates CMake source lists for BTstack.
#
# Lists are grouped so a consumer can take a whole list or skip it.
# The aim is that it should not be necessary to pick files out of a source list.
# Anything mutually exclusive - transports, link key / device db backends,
# TLV backends, run loops, codecs, etc. has its own list.
#
# Files that no rule matches are listed in BTSTACK_UNCLASSIFIED_SOURCES and
# reported on stderr, so a consumer can check that the lists it expects still exist.
#
# Usage:
#   python3 tool/create_cmake_sources.py
#
# Re-run after adding source files.
# CI can check that running the tool has no effect.

